"""字母玩法：把 A–Z 的字模栅格化成棋盘遮罩。

基础玩法的 12 关铺在「形状」里（圆、心、菱形……），字母玩法的 26 关则是
**整盘铺成一个字母**：先用一套 5×7 的点阵字模定义笔画，再按 ``scale``
放大成棋盘格子，线段只铺在笔画内部，于是每一关看着就是一个大字母。

## 为什么字模只要八连通

点阵里 ``C``、``S``、``J``、``Q`` 这类带斜笔的字母，笔画在点阵层面是
**对角相接**的。放大之后两个相邻的像素方块共享一个角点，看起来是一笔
连下来的；线段的铺设也不受影响 —— 生成器只在四邻域内长身体，对角相接
的两个「岛」各自独立放箭，飞出去时互不干扰。

所以这里的连通性检查用八连通（``shapes.is_connected(cells, diagonal=True)``），
比四连通宽松一档，但足以保证「每个字母是一整块、不会有一撮孤零零的
碎格」。字模本身也做过一次人工复核：没有一个字母被拆成两半。
"""

