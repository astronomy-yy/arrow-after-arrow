PATTERN_COLS = 5
PATTERN_ROWS = 7

# 字模 -> 棋盘的放大倍数与四周留白（都给一致的值，26 关的棋盘尺寸相同）
# scale=3 时棋盘是 23 行 × 17 列：每个笔画像素展开成 3×3 的方块，字母的
# 弧线与斜笔（C、S、J、Q）比 scale=2 平滑得多，盘面格子数也从 192 涨到 391。
DEFAULT_SCALE = 3
DEFAULT_MARGIN = 1

LETTERS = tuple(sorted(LETTER_PATTERNS))


def is_letter(value):
    """是不是一个合法的字母关标识。"""
    return isinstance(value, str) and value.upper() in LETTER_PATTERNS


def board_size(scale=DEFAULT_SCALE, margin=DEFAULT_MARGIN):
    """字母关的棋盘尺寸，返回 ``(行数, 列数)`` —— 与别处的 rows/cols 同序。"""
    return (PATTERN_ROWS * scale + margin * 2,
            PATTERN_COLS * scale + margin * 2)


def pattern(letter):
    """取字母的点阵行（大写）。"""
    key = str(letter).upper()
    if key not in LETTER_PATTERNS:
        raise KeyError(f"没有这个字母的字模：{letter}")
    return LETTER_PATTERNS[key]


def on_pixels(letter):
    """字模里所有笔画像素的 (行, 列)。"""
    rows = pattern(letter)
    return [(r, c) for r, line in enumerate(rows)
            for c, ch in enumerate(line) if ch == "#"]


def letter_cells(rows, cols, letter, scale=DEFAULT_SCALE,
                 margin=DEFAULT_MARGIN):
    """把字母栅格化成 ``rows x cols`` 棋盘上的遮罩格子。

    每个笔画像素展开成 ``scale x scale`` 的方块；棋盘比字模大出来的那圈
    （``margin``）留空，线段因此不会贴着棋盘边缘，看着舒服一些。
    """
    cells = set()
    for (r, c) in on_pixels(letter):
        for dr in range(scale):
            for dc in range(scale):
                rr = margin + r * scale + dr
                cc = margin + c * scale + dc
                if 0 <= rr < rows and 0 <= cc < cols:
                    cells.add((rr, cc))
    return cells


def preview(letter, scale=1, margin=0):
    """调试用：把字母的遮罩画成字符画。"""
    rows, cols = board_size(scale, margin)
    cells = letter_cells(rows, cols, letter, scale, margin)
    return "\n".join(
        "".join("#" if (r, c) in cells else "." for c in range(cols))
        for r in range(rows)
    )
